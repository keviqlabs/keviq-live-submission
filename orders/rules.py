"""Permission layer (C6). Every decision returns a reason that goes into the order event and the console.

Invariants (tests/test_rules_invariants.py):
  - no CONFIRMED order without the customer's confirmation (orders/states.py);
  - no discount, price change or refund without seller approval;
  - there is no code path that collects money or promises delivery outside policy.
Do not edit this file without editing the tests in the same change.
"""

from dataclasses import dataclass

# Mirrors contracts/permissions.json; tests/test_rules_invariants.py fails if the two drift.
PERMISSIONS = {
    "create_draft_card": "auto",
    "answer_product_question": "auto",
    "draft_order": "auto",
    "send_confirmation": "auto",
    "hide_comment_contact_or_link": "auto",
    "discount": "seller",
    "order_over_threshold": "seller",
    "refund": "seller",
    "change_address_after_confirm": "seller",
    "collect_payment": "forbidden",
    "promise_delivery_outside_policy": "forbidden",
    "message_outside_24h": "forbidden",
}
SELLER_THRESHOLD_VND = 2_000_000
MESSAGE_WINDOW_MS = 24 * 3600 * 1000


@dataclass(frozen=True)
class Decision:
    allowed: bool
    needs_seller: bool
    reason: str


def authorize(action: str, actor: str = "assistant", approved_by_seller: bool = False) -> Decision:
    decision = PERMISSIONS.get(action)
    if decision is None:
        return Decision(False, False, f"unknown action {action}: denied")
    if decision == "forbidden":
        return Decision(False, False, f"{action} is forbidden")
    if decision == "seller":
        if actor == "seller" or approved_by_seller:
            return Decision(True, False, f"{action} approved by seller")
        return Decision(False, True, f"{action} needs seller approval")
    return Decision(True, False, f"{action} is automatic")


def can_message(last_customer_message_ms: int | None, now_ms: int) -> Decision:
    if last_customer_message_ms is None:
        return Decision(False, False, "no customer message to reply to")
    if now_ms - last_customer_message_ms > MESSAGE_WINDOW_MS:
        return Decision(False, False, "outside 24h since the customer's last message")
    return Decision(True, False, "within 24h window")


def evaluate_draft(
    unit_price: int | None,
    card_price: int | None,
    qty: int,
    stock: int,
    discount_requested: bool = False,
    threshold: int = SELLER_THRESHOLD_VND,
) -> Decision:
    """Checks for an assistant-drafted order line. Agent 3 extends this; keep the decision shape."""
    if card_price is None:
        return Decision(False, True, "card has no price yet")
    if discount_requested:
        return Decision(False, True, "customer asked for a discount: waiting for the shop")
    if unit_price != card_price:
        return Decision(False, True, f"unit price {unit_price} != live card price {card_price}")
    if qty > stock:
        return Decision(False, True, f"qty {qty} > stock {stock}")
    if unit_price * qty > threshold:
        return Decision(False, True, f"amount {unit_price * qty} > seller threshold {threshold}")
    return Decision(True, False, "price matches live card, qty within stock")
