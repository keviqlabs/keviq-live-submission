const LANG_KEY = "keviq.lang";
const LANGS = Object.keys(I18N);
let lang = "en";

function queryParam(name) {
  const search = typeof location !== "undefined" && location.search ? location.search : "";
  const m = new RegExp(`[?&]${name}=([^&#]*)`).exec(search);
  return m ? decodeURIComponent(m[1].replace(/\+/g, " ")) : null;
}

function storedLang() {
  try { return typeof localStorage !== "undefined" ? localStorage.getItem(LANG_KEY) : null; } catch { return null; }
}

// ?lang= wins, then the stored choice, then English.
function currentLang() {
  const fromQuery = queryParam("lang"), stored = storedLang();
  lang = LANGS.includes(fromQuery) ? fromQuery : LANGS.includes(stored) ? stored : "en";
  return lang;
}

function t(key, vars) {
  let s = I18N[lang]?.[key] ?? I18N.en[key];
  if (s == null) return key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

// Translate a value from an enumerated event field; unknown values stay as data.
function tEnum(prefix, value) {
  const key = `${prefix}.${value}`;
  return I18N.en[key] != null ? t(key) : String(value ?? "");
}

// Static text: elements with data-i18n get their text, data-i18n-attr="attr:key,attr:key" their attributes.
function applyStaticText() {
  if (typeof document === "undefined" || typeof document.querySelectorAll !== "function") return;
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of el.dataset.i18nAttr.split(",")) {
      const [attr, key] = pair.split(":");
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    }
  }
  for (const b of document.querySelectorAll("[data-lang]")) {
    const selected = b.dataset.lang === lang;
    b.className = selected ? "active" : "";
    b.setAttribute("aria-pressed", String(selected));
  }
  if (document.documentElement) document.documentElement.lang = lang;
}

function setLang(next, onChange) {
  if (!LANGS.includes(next)) return;
  lang = next;
  try { if (typeof localStorage !== "undefined") localStorage.setItem(LANG_KEY, next); } catch { /* storage is optional */ }
  applyStaticText();
  if (onChange) onChange(next);
}
